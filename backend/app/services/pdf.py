"""Quotation PDFs with ReportLab. Built only from the quotation snapshot, never from live prices.

Customer-facing: shows unit price (markup included), VAT and total; never the internal material
costs or markup. All user-provided text is escaped before it reaches ReportLab's markup parser.
"""

from dataclasses import dataclass
from datetime import date, datetime
from decimal import Decimal
from io import BytesIO
from typing import Any
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.pdfgen.canvas import Canvas
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.services.quotations import PHT

BRAND = colors.HexColor("#1f5fa8")
MUTED = colors.HexColor("#666666")
UNITS = {"cm": "cm", "in": "in"}


@dataclass(frozen=True)
class PdfInput:
    snapshot: dict[str, Any]
    business: dict[str, Any]
    reference: str  # quote number, or DRAFT-xxxxxxxx
    created_at: datetime
    valid_until: date | None
    draft: bool
    note: str | None = None


def _styles() -> dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()
    body = ParagraphStyle(
        "body", parent=base["Normal"], fontName="Helvetica", fontSize=9.5, leading=13
    )
    return {
        "body": body,
        "small": ParagraphStyle("small", parent=body, fontSize=8, leading=10.5, textColor=MUTED),
        "business": ParagraphStyle(
            "business",
            parent=body,
            fontName="Helvetica-Bold",
            fontSize=15,
            leading=19,
            textColor=BRAND,
        ),
        "title": ParagraphStyle(
            "title",
            parent=body,
            fontName="Helvetica-Bold",
            fontSize=18,
            leading=22,
            alignment=TA_RIGHT,
        ),
        "right": ParagraphStyle("right", parent=body, alignment=TA_RIGHT),
        "heading": ParagraphStyle(
            "heading",
            parent=body,
            fontName="Helvetica-Bold",
            fontSize=10.5,
            spaceBefore=6,
            spaceAfter=3,
        ),
    }


def _p(text: str, style: ParagraphStyle) -> Paragraph:
    """Paragraph from untrusted text: escaped, newlines kept."""
    return Paragraph(escape(text).replace("\n", "<br/>"), style)


def _money(amount: str | Decimal, currency: str) -> str:
    return f"{currency} {Decimal(amount):,.2f}"


def _num(value: str) -> str:
    """ "120.00" -> "120", "47.25" -> "47.25"."""
    return format(Decimal(value).normalize(), "f")


def _date(d: date | datetime) -> str:
    if isinstance(d, datetime):
        d = d.astimezone(PHT).date()
    return d.strftime("%B %d, %Y").replace(" 0", " ")


def _watermark(canvas: Canvas, _doc: Any) -> None:
    canvas.saveState()
    canvas.setFillColor(colors.red)
    canvas.setFillAlpha(0.12)
    canvas.translate(A4[0] / 2, A4[1] / 2)
    canvas.rotate(35)
    canvas.setFont("Helvetica-Bold", 72)
    canvas.drawCentredString(0, 10, "ESTIMATE")
    canvas.setFont("Helvetica-Bold", 26)
    canvas.drawCentredString(0, -28, "PENDING APPROVAL")
    canvas.restoreState()


def _footer(canvas: Canvas, doc: Any) -> None:
    canvas.saveState()
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(MUTED)
    canvas.drawString(18 * mm, 10 * mm, "Generated by AQS APP - Automatic Quotation System")
    canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def render_quotation_pdf(data: PdfInput) -> bytes:
    s = _styles()
    snap = data.snapshot
    pricing = snap["pricing"]
    currency = pricing["currency"]
    customer = snap["customer"]
    product = snap["product"]
    inp = snap["input"]
    unit = UNITS.get(inp["unit"], inp["unit"])

    story: list[Any] = []

    # Header: business on the left, document info on the right.
    business_block = [_p(data.business.get("name") or "", s["business"])]
    if data.business.get("address"):
        business_block.append(_p(data.business["address"], s["small"]))
    if data.business.get("contact"):
        business_block.append(_p(data.business["contact"], s["small"]))
    info = [
        Paragraph("ESTIMATE" if data.draft else "QUOTATION", s["title"]),
        _p(f"No.: {data.reference}", s["right"]),
        _p(f"Date: {_date(data.created_at)}", s["right"]),
        _p(
            f"Valid until: {_date(data.valid_until)}"
            if data.valid_until
            else "Valid until: issued upon approval",
            s["right"],
        ),
    ]
    header = Table([[business_block, info]], colWidths=[96 * mm, 72 * mm], hAlign="LEFT")
    header.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 0),
                ("RIGHTPADDING", (0, 0), (-1, -1), 0),
            ]
        )
    )
    story += [header, Spacer(1, 8 * mm)]

    # Customer
    story.append(Paragraph("Prepared for", s["heading"]))
    for line in (
        customer["full_name"],
        customer["address_line"],
        f"{customer['city']}, {customer['province']}",
        f"{customer['contact_number']}  |  {customer['email']}",
    ):
        story.append(_p(line, s["body"]))
    story.append(Spacer(1, 6 * mm))

    # Item
    includes = ", ".join(line["label"] or line["name"] for line in pricing["lines"])
    description = [_p(product["name"], s["body"])]
    if product.get("description"):
        description.append(_p(product["description"], s["small"]))
    description.append(_p(f"Includes: {includes}", s["small"]))
    size = (
        f"{_num(inp['width'])} x {_num(inp['height'])} {unit}\n"
        f"({pricing['width_mm']} x {pricing['height_mm']} mm)"
    )
    rows = [
        ["Description", "Size", "Qty", "Unit price", "Amount"],
        [
            description,
            _p(size, s["body"]),
            str(pricing["quantity"]),
            _money(pricing["unit_price"], currency),
            _money(pricing["net"], currency),
        ],
    ]
    vat_label = f"VAT {_num(pricing['vat_percent'])}%"
    totals = [
        ["", "", "", "Subtotal", _money(pricing["net"], currency)],
        ["", "", "", vat_label, _money(pricing["vat"], currency)],
        ["", "", "", "Total", _money(pricing["total"], currency)],
    ]
    # Widths sum to 168 mm: fits the 174 mm text area minus ReportLab's 6 pt frame padding.
    table = Table(
        rows + totals, colWidths=[62 * mm, 34 * mm, 11 * mm, 29 * mm, 32 * mm], hAlign="LEFT"
    )
    table.setStyle(
        TableStyle(
            [
                ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 9),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("BACKGROUND", (0, 0), (-1, 0), BRAND),
                ("FONT", (0, 1), (-1, -1), "Helvetica", 9.5),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("ALIGN", (2, 0), (-1, -1), "RIGHT"),
                ("LINEBELOW", (0, 1), (-1, 1), 0.5, colors.lightgrey),
                ("FONT", (3, -1), (-1, -1), "Helvetica-Bold", 11),
                ("LINEABOVE", (3, -1), (-1, -1), 1, colors.black),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )
    story += [table, Spacer(1, 8 * mm)]

    if data.note:
        story += [Paragraph("Note", s["heading"]), _p(data.note, s["body"]), Spacer(1, 4 * mm)]
    if data.business.get("terms"):
        story += [
            Paragraph("Terms and conditions", s["heading"]),
            _p(data.business["terms"], s["small"]),
        ]

    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=18 * mm,
        title=f"{'Estimate' if data.draft else 'Quotation'} {data.reference}",
        author=data.business.get("name") or "AQS APP",
    )

    def on_page(canvas: Canvas, d: Any) -> None:
        if data.draft:
            _watermark(canvas, d)
        _footer(canvas, d)

    doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return buffer.getvalue()
